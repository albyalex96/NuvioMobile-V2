private val enhancedSettingsSearchKeyPrefixes = listOf("tv-remote-", "tv-layout-", "live-tv-", "discord-rpc-", "app-logs-", "media-proxy-", "cloudstream", "top10")

internal val SettingsSearchEntry.isEnhancedFeature: Boolean
    get() = key in enhancedSettingsSearchKeys ||
        enhancedSettingsSearchKeyPrefixes.any { key.startsWith(it) } ||
        (target as? SettingsSearchTarget.Page)?.page in enhancedSettingsPages
